// req-138 — review aids for the library text pass (a one-off, not a test).
//
//   node scripts/library-text-report.mjs
//
// Writes reports/req-138-library-text.md (all common entries, grouped by pattern then
// family) and prints the review aids as markdown (the dump: one entry per pattern plus the
// named staples; near-duplicate steps within a family; muscles named in a description
// that aren't tagged) for the req report.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { isUnderMuscle, MUSCLE_TREE, PATTERNS, shownName } from '../src/exerciseLibrary.js'

const root = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url))
const library = JSON.parse(readFileSync(root('src/library/exercises.json'), 'utf8'))
const common = library.filter((entry) => entry.common)

const STAPLES = [
  'Barbell_Bench_Press_-_Medium_Grip', 'Barbell_Squat', 'Barbell_Deadlift', 'Pullups', 'Bent_Over_Barbell_Row',
  'Standing_Military_Press', 'Romanian_Deadlift', 'Barbell_Hip_Thrust', 'Wide-Grip_Lat_Pulldown', 'Leg_Press',
  'Dumbbell_Bench_Press', 'Incline_Dumbbell_Press', 'Dumbbell_Shoulder_Press', 'Dumbbell_Bicep_Curl', 'Triceps_Pushdown',
  'Side_Lateral_Raise', 'Seated_Leg_Curl', 'Leg_Extensions', 'Plank', 'Pushups', 'Dumbbell_Lunges', 'Face_Pull',
]

const muscleText = (entry) => entry.muscles.map((m) => (m.role === 'primary' ? `**${m.id}**` : m.id)).join(', ')
function block(entry) {
  return [
    `#### ${shownName(entry)} — \`${entry.id}\``,
    '',
    `${entry.pattern} · ${entry.family} · ${entry.logAs}${entry.unilateral ? ' · unilateral' : ''} · ${entry.equipmentList.join(', ')} · ${muscleText(entry)}`,
    '',
    `> ${entry.description}`,
    '',
    `**Form cues:** ${entry.formCues.join(' · ')}`,
    '',
    '**Steps:**',
    '',
    ...entry.steps.map((step, i) => `${i + 1}. ${step}`),
    '',
    `**Mistakes:** ${entry.mistakes.join(' · ')}`,
    '',
  ].join('\n')
}

// Full file: pattern (PATTERNS order), then family (first-seen order).
const full = ['# req-138 — library text, all common entries', '', `${common.length} entries, grouped by pattern then family. Generated by \`scripts/library-text-report.mjs\`.`, '']
for (const pattern of PATTERNS) {
  const inPattern = common.filter((entry) => entry.pattern === pattern)
  if (!inPattern.length) continue
  full.push(`## ${pattern} (${inPattern.length})`, '')
  for (const family of [...new Set(inPattern.map((entry) => entry.family))]) {
    full.push(`### ${family}`, '')
    for (const entry of inPattern.filter((item) => item.family === family)) full.push(block(entry))
  }
}
writeFileSync(root('reports/req-138-library-text.md'), `${full.join('\n').trimEnd()}\n`)

// Dump: a staple stands in for its pattern where there is one, so overlaps drop out.
const patterns = PATTERNS.filter((pattern) => common.some((entry) => entry.pattern === pattern))
const perPattern = patterns.map((pattern) =>
  STAPLES.find((id) => common.find((entry) => entry.id === id)?.pattern === pattern)
  || common.find((entry) => entry.pattern === pattern).id)
const dumpIds = [...new Set([...perPattern, ...STAPLES])]

// Near-duplicates: steps token Jaccard > 0.85 within a family.
const tokenSet = (entry) => new Set(entry.steps.join(' ').toLowerCase().match(/[a-z0-9°]+/g) || [])
const nearDups = []
for (const family of new Set(common.map((entry) => entry.family))) {
  const members = common.filter((entry) => entry.family === family)
  for (let i = 0; i < members.length; i += 1) {
    for (let j = i + 1; j < members.length; j += 1) {
      const a = tokenSet(members[i])
      const b = tokenSet(members[j])
      const inter = [...a].filter((t) => b.has(t)).length
      const jaccard = inter / (a.size + b.size - inter)
      nearDups.push({ family, a: members[i].id, b: members[j].id, jaccard })
    }
  }
}
nearDups.sort((x, y) => y.jaccard - x.jaccard)
const flaggedDups = nearDups.filter((pair) => pair.jaccard > 0.85)

// Muscle mismatch: a tree label or alias named in the description whose node is not a
// tagged muscle, nor an ancestor or descendant of one. Longest phrase first, so "upper
// back" is read before "back".
const phrases = Object.entries(MUSCLE_TREE)
  .flatMap(([id, node]) => [node.label, ...node.aliases].map((phrase) => ({ id, phrase: phrase.toLowerCase() })))
  .sort((a, b) => b.phrase.length - a.phrase.length)
const mismatches = []
for (const entry of common) {
  let text = entry.description.toLowerCase()
  // The part after "trains/works/targets/…" is what the sentence claims is trained.
  const verb = text.search(/\b(train|work|target|isolat|shift|stretch|challeng)\w*/)
  const tagged = entry.muscles.map((m) => m.id)
  for (const { id, phrase } of phrases) {
    const pattern = new RegExp(`\\b${phrase.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}\\b`)
    const at = text.search(pattern)
    if (at < 0) continue
    text = text.replace(pattern, (match) => ' '.repeat(match.length))
    const related = tagged.some((t) => isUnderMuscle(t, id) || isUnderMuscle(id, t))
    if (!related) mismatches.push({ id: entry.id, phrase, node: id, tagged, claimed: verb >= 0 && at > verb })
  }
}

const aids = [
  '# req-138 — review aids',
  '',
  `## Dump (${dumpIds.length}: one per pattern — ${patterns.length} patterns — plus the ${STAPLES.length} staples, overlaps removed)`,
  '',
  ...dumpIds.map((id) => block(common.find((entry) => entry.id === id))),
  `## Near-duplicate steps within a family (Jaccard > 0.85): ${flaggedDups.length}`,
  '',
  ...(flaggedDups.length ? flaggedDups.map((p) => `- ${p.family}: \`${p.a}\` / \`${p.b}\` — ${p.jaccard.toFixed(2)}`) : ['None.']),
  '',
  'Closest pairs (for scale):',
  '',
  ...nearDups.slice(0, 5).map((p) => `- ${p.family}: \`${p.a}\` / \`${p.b}\` — ${p.jaccard.toFixed(2)}`),
  '',
  `## Muscle mismatch (informational): ${mismatches.length}`,
  '',
  'A tree label or alias in the description whose node is not tagged, nor above or below a tagged node.',
  '',
  `**Named as trained** (after "trains/works/targets…"): ${mismatches.filter((m) => m.claimed).length}`,
  '',
  ...mismatches.filter((m) => m.claimed).map((m) => `- \`${m.id}\`: "${m.phrase}" → ${m.node}; tagged ${m.tagged.join(', ')}`),
  '',
  `**Named as body position or equipment** (before the verb, e.g. "on your back", "close-grip"): ${mismatches.filter((m) => !m.claimed).length}`,
  '',
  ...mismatches.filter((m) => !m.claimed).map((m) => `- \`${m.id}\`: "${m.phrase}" → ${m.node}`),
  '',
]
process.stdout.write(`${aids.join('\n').trimEnd()}\n`)
console.error(`wrote reports/req-138-library-text.md (${common.length} entries); aids: dump ${dumpIds.length}, near-dups ${flaggedDups.length}, mismatches ${mismatches.length}`)
